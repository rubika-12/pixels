export function getPnLSummary(records = PNL_RECORDS) {
  const totalNetRealized = records.reduce((acc, r) => acc + (r.realizedNet || 0), 0);
  const totalExtraGain = records.reduce((acc, r) => acc + (r.profitGain || 0), 0);
  const totalSpoilageSavedKg = records.reduce((acc, r) => acc + (r.spoilageAvoidedKg || 0), 0);
  const totalQuantityKg = records.reduce((acc, r) => acc + (r.quantityKg || 0), 0);

  return {
    totalNetRealized,
    totalExtraGain,
    totalSpoilageSavedKg,
    totalQuantityKg,
    totalLots: records.length,
  };
}
